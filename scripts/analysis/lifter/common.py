def write_if_changed(path: Path, content: str) -> bool:
    """Write content to path only if it differs from current disk content.
    Prevents unnecessary mtime updates and full project rebuilds in Ninja."""
    if path.exists():
        try:
            with open(path, "r", encoding="utf-8") as f:
                if f.read() == content:
                    return False
        except Exception:
            pass
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    return True


_SHARED_CS = None


def get_shared_cs():
    """Singleton Capstone context to avoid expensive reinstantiation overhead."""
    global _SHARED_CS
    if _SHARED_CS is None and Cs is not None:
        _SHARED_CS = Cs(CS_ARCH_X86, CS_MODE_32)
        _SHARED_CS.detail = True
    return _SHARED_CS
