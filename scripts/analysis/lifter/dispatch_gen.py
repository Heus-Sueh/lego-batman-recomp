def generate_recomp_funcs_h(out_dir: Path, functions: list[dict]):
    lines = [
        HEADER_COMMENT,
        "#pragma once",
        "#include <cstdint>",
        "",
        'extern "C" {'
    ]

    for fn in sorted(functions, key=lambda x: x["rva"]):
        rva = fn["rva"]
        name = fn.get("name", "unknown")
        lines.append(f"void recomp_func_{rva:08X}(void); // {name}")

    lines.append("}")
    lines.append("")
    lines.append("// Register all generated functions into runtime dispatch table")
    lines.append("void register_generated_recomp_functions();")
    lines.append("")

    write_if_changed(out_dir / "recomp_funcs.h", "\n".join(lines))


